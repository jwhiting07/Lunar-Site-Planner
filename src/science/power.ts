/**
 * Solar power and battery energy estimate. [M-POWER] [M-BATTERY]
 *
 * ENGINEERING ESTIMATE based on assumed lander parameters (constants.ts
 * DEFAULT_LANDER, [A-LANDER]); it is not a simulation of any NASA CLPS
 * spacecraft. No thermal, degradation, attitude or power-distribution effects.
 */
import {
  AU_KM,
  DEG,
  HOUR_MS,
  INITIAL_STATE_OF_CHARGE,
  SOLAR_CONSTANT_W_M2,
  type LanderParams,
  type PanelMode,
} from './constants';

/**
 * Solar irradiance at distance `distKm` from the Sun, W/m^2: inverse-square
 * scaling of the total solar irradiance at 1 au, S(r) = S0 (au / r)^2. [R-TSI] [R-AU]
 */
export function solarFluxWm2(distKm: number): number {
  const ratio = AU_KM / distKm;
  return SOLAR_CONSTANT_W_M2 * ratio * ratio;
}

/**
 * Fraction of a uniform circular disk of angular radius `radiusDeg` that lies
 * above a straight horizontal edge when the disk centre is `clearanceDeg`
 * above the edge. With x = clearance / radius, |x| < 1:
 *   f = 1 - (acos(x) - x sqrt(1 - x^2)) / pi      (circular-segment area) [R-SEGMENT]
 * APPROXIMATION: the horizon is treated as straight and level across the
 * ~0.53 deg solar disk and limb darkening is ignored.
 */
export function diskFractionVisible(clearanceDeg: number, radiusDeg: number): number {
  const x = clearanceDeg / radiusDeg;
  if (x >= 1) return 1;
  if (x <= -1) return 0;
  return 1 - (Math.acos(x) - x * Math.sqrt(1 - x * x)) / Math.PI;
}

/**
 * cos(incidence angle) between the panel normal and the Sun-centre direction
 * for the three pointing assumptions (Lambert cosine law):
 *   tracking   - two-axis Sun tracking, normal . sun = 1
 *   vertical   - vertical panel rotating in azimuth to face the Sun, = cos(elevation)
 *   horizontal - fixed panel facing the zenith, = max(0, sin(elevation))
 */
export function incidenceFactor(mode: PanelMode, sunElevationDeg: number): number {
  const el = sunElevationDeg * DEG;
  if (mode === 'tracking') return 1;
  if (mode === 'vertical') return Math.cos(el);
  return Math.max(0, Math.sin(el));
}

/**
 * Electrical power from the array, W:
 *   P = S(r) * A * eta * cos(incidence) * f_disk
 * where f_disk is the visible fraction of the solar disk (so a Sun that is
 * only partly above the terrain does not produce full power).
 */
export function panelPowerW(
  params: LanderParams,
  sunDistKm: number,
  sunElevationDeg: number,
  diskFraction: number,
): number {
  return (
    solarFluxWm2(sunDistKm) *
    params.panelAreaM2 *
    params.panelEfficiency *
    incidenceFactor(params.panelMode, sunElevationDeg) *
    diskFraction
  );
}

export interface BatteryResult {
  /** Stored energy at each sample time, Wh. */
  energyWh: Float64Array;
  /** Energy generated by the array over the interval, Wh. */
  generatedWh: number;
  /** Energy demanded by the constant load over the interval, Wh. */
  loadWh: number;
  /** Load energy that could not be supplied (battery empty), Wh. */
  unservedWh: number;
  /** Total time the load could not be fully supplied, h. */
  deficitHours: number;
  /** Lowest stored energy reached, Wh, and when. */
  minEnergyWh: number;
  minEnergyTimeMs: number;
  /** Time at which the battery first ran empty, or null. */
  firstDeficitMs: number | null;
  /** Generated energy that could not be stored or used (battery full), Wh. */
  curtailedWh: number;
}

/**
 * Energy-balance integration with explicit time stepping:
 *   E_gen,i  = (P_i + P_{i+1}) / 2 * dt          (trapezoidal rule)
 *   Integrate linear net power exactly, splitting at its zero crossing and
 *   solving the empty/full crossing within each monotone-energy segment.
 * ASSUMPTIONS: ideal storage (100 % charge/discharge efficiency), constant
 * load, battery starts at INITIAL_STATE_OF_CHARGE. Energy below 0 is counted as
 * unserved load. A step that first discharges then charges must not cancel the
 * intervening deficit, or hide its interior minimum charge.
 */
export function simulateBattery(
  tMs: ArrayLike<number>,
  powerW: ArrayLike<number>,
  params: LanderParams,
): BatteryResult {
  const n = tMs.length;
  const cap = params.batteryCapacityWh;
  const energyWh = new Float64Array(n);
  let e = cap * INITIAL_STATE_OF_CHARGE;
  let generatedWh = 0, loadWh = 0, unservedWh = 0, deficitHours = 0, curtailedWh = 0;
  let minEnergyWh = e;
  let minEnergyTimeMs = n > 0 ? tMs[0] : NaN;
  let firstDeficitMs: number | null = null;
  if (n > 0) energyWh[0] = e;
  for (let i = 0; i < n - 1; i++) {
    const dtH = (tMs[i + 1] - tMs[i]) / HOUR_MS;
    const gen = 0.5 * (powerW[i] + powerW[i + 1]) * dtH;
    const load = params.loadW * dtH;
    generatedWh += gen;
    loadWh += load;
    const p0 = powerW[i] - params.loadW, p1 = powerW[i + 1] - params.loadW;
    const slope = (p1 - p0) / dtH;
    const turn = p0 * p1 < 0 ? -p0 / slope : dtH;
    const cuts = turn < dtH ? [0, turn, dtH] : [0, dtH];
    for (let k = 0; k < cuts.length - 1; k++) {
      const a = cuts[k], duration = cuts[k + 1] - a, rate = p0 + slope * a;
      const integral = (h: number) => rate * h + 0.5 * slope * h * h;
      const net = integral(duration), next = e + net;
      if (next < 0 || next > cap) {
        const target = next < 0 ? -e : cap - e;
        let lo = 0, hi = duration;
        // Monotone integral on this segment; bisection avoids cancellation in
        // quadratic roots for almost constant generation.
        for (let z = 0; z < 40; z++) {
          const mid = (lo + hi) / 2;
          if ((net < 0 ? -1 : 1) * (integral(mid) - target) < 0) lo = mid; else hi = mid;
        }
        const hit = (lo + hi) / 2;
        if (next < 0) {
          unservedWh += -next;
          deficitHours += duration - hit;
          if (firstDeficitMs === null) firstDeficitMs = tMs[i] + (a + hit) * HOUR_MS;
          e = 0;
        } else { curtailedWh += next - cap; e = cap; }
        if (e < minEnergyWh) {
          minEnergyWh = e;
          minEnergyTimeMs = tMs[i] + (a + hit) * HOUR_MS;
        }
      } else e = next;
      if (e < minEnergyWh) { minEnergyWh = e; minEnergyTimeMs = tMs[i] + cuts[k + 1] * HOUR_MS; }
    }
    energyWh[i + 1] = e;
    if (e < minEnergyWh) {
      minEnergyWh = e;
      minEnergyTimeMs = tMs[i + 1];
    }
  }
  return {
    energyWh, generatedWh, loadWh, unservedWh, deficitHours,
    minEnergyWh, minEnergyTimeMs, firstDeficitMs, curtailedWh,
  };
}
